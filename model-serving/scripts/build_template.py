#!/usr/bin/env python3
"""Embed the local skill into the official template without modifying model files."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    skill = ROOT / "skills/natural-chinese/SKILL.md"
    source = ROOT / "models/Qwen3.8-27B/chat_template.jinja"
    content = skill.read_text(encoding="utf-8")
    if not content.startswith("---\n") or "\n---\n" not in content[4:]:
        raise ValueError("Skill must contain YAML frontmatter")
    body = content.split("\n---\n", 1)[1].strip()
    prompt = "你是一个认真、可靠的中文助手。遵守以下表达要求：\n\n" + body
    # Add after render_content is defined so system messages containing text
    # arrays keep the same validation and rendering as the upstream template.
    original = source.read_text(encoding="utf-8")
    anchor = "{%- set reasoning_instructions = '' %}"
    if original.count(anchor) != 1:
        raise ValueError("Official template changed; inspect it before updating")
    addition = (
        "{# Local natural-chinese skill; generated by scripts/build_template.py #}\n"
        "{%- set chinese_style = " + json.dumps(prompt, ensure_ascii=False) + " -%}\n"
        "{%- if messages[0].role == 'system' -%}\n"
        "  {%- set previous_system = render_content(messages[0].content, false, true)|trim -%}\n"
        "  {%- set messages = [{'role': 'system', 'content': previous_system ~ '\\n\\n' ~ chinese_style}] + messages[1:] -%}\n"
        "{%- else -%}\n"
        "  {%- set messages = [{'role': 'system', 'content': chinese_style}] + messages -%}\n"
        "{%- endif -%}\n"
    )
    (ROOT / "chat_template.jinja").write_text(original.replace(anchor, addition + anchor), encoding="utf-8")
    (ROOT / "system-prompt.txt").write_text(prompt + "\n", encoding="utf-8")
    (ROOT / "template-provenance.json").write_text(json.dumps({
        "skill_sha256": hashlib.sha256(content.encode()).hexdigest(),
        "upstream_template_sha256": hashlib.sha256(original.encode()).hexdigest(),
        "source": "https://modelscope.cn/models/Qwen/Qwen3.8-27B",
    }, indent=2) + "\n")
    print("Built chat_template.jinja and system-prompt.txt")


if __name__ == "__main__":
    build()
